"""Сортировка «Популярные» (по умолчанию на витрине).

Продаж в данных нет, поэтому «ходовость» — эвристика:
  хиты (модели с лендинга и наши Мустанги) → наверх;
  легковые бортовые/тентованные до 750 кг в ходовой цене → выше;
  аксессуары, «цена по запросу», тяжёлая техника → вниз;
  карточка с фото/описанием/характеристиками → выше.
Потом жадно разбавляем выдачу, чтобы первые экраны не были сплошь МЗСА.
Результат — поле rank (0 = первый), JS сортирует по нему.
"""

# Модели, выставленные на лендинге восток-прицеп.рф, + наши Мустанги
HITS = {
    '211635904242': 100,  # Титан 3015-03
    '456814217732': 100,  # Трейлер 829450 3,0×1,5
    '310437250562': 100,  # Крепыш 2.5 Плюс
    '422304639672': 100,  # Славич 255Д двухосный
    '552929326102': 100,  # ALASKA Скала 3.5
    '571166159772': 100,  # МЗСА 817701.026 с крышкой
    '770000000203': 70, '770000000255': 70, '770000000325': 70, '770000001325': 70,  # Мустанг
}

KIND_W = {
    'Бортовой': 30, 'С тентом': 28, 'С крышкой': 22, 'Лодочный': 18,
    'Для мототехники': 14, 'Самосвальный': 14, 'Платформа': 10, 'Коммерческий': 8,
    'Фургон': 6, 'Эвакуатор': 6, 'Полуприцеп': 4, 'Дом на колёсах': 4, 'Коневоз': 3,
    'Аксессуар': -80,
}


def score(p):
    s = HITS.get(p['id'], 0) + KIND_W.get(p['kind'], 0)
    pr = p['price']
    if not pr:            s -= 40   # «цена по запросу»
    elif pr < 25000:      s -= 15
    elif pr < 35000:      s += 5
    elif pr <= 130000:    s += 20   # основной спрос на легковые
    elif pr <= 250000:    s += 10
    elif pr > 600000:     s -= 10
    s += {'750': 8, '3500': 0, 'hi': -8}.get(p['massCat'], -4)
    n = len(p['imgs'])
    s += min(n, 8) * 1.5 - (8 if n < 2 else 0)
    s += min(len(p.get('about') or '') / 200, 5) + min(len(p.get('pros') or []), 5) * 0.6
    s += -10 if p['brand'] == 'Другой' else 0
    s += 2 if p.get('galv') else 0
    return s


def assign_ranks(items):
    """Жадно: каждый следующий — лучший по score со штрафом за повтор марки/типа подряд."""
    left = sorted(items, key=lambda p: -score(p))
    base = {p['id']: score(p) for p in left}
    out = []
    while left:
        recent_b = [q['brand'] for q in out[-6:]]
        recent_k = [q['kind'] for q in out[-3:]]
        best = max(left[:60], key=lambda p: base[p['id']]
                   - 9 * recent_b.count(p['brand']) - 4 * recent_k.count(p['kind']))
        left.remove(best)
        out.append(best)
    for i, p in enumerate(out):
        p['rank'] = i
